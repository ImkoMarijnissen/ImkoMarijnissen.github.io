#!/usr/bin/env python3
"""Add the publications from the BibTeX bibliography to the RenderCV input.

Reads the CV (_data/cv.yml) and the bibliography (_bibliography/papers.bib), converts every
BibTeX entry into a RenderCV publication entry and writes the CV with a "Publications" section
to a separate file, which is what RenderCV renders. The publications are generated rather than
written into _data/cv.yml so that papers.bib stays the single source of truth.

The output file starts with a dot so Jekyll ignores it; it is also listed in .gitignore.

Usage:
    python bin/rendercv_publications.py [--cv _data/cv.yml] [--bib _bibliography/papers.bib]
                                        [--output _data/.cv_with_publications.yml]
    rendercv render _data/.cv_with_publications.yml --settings assets/rendercv/settings.yaml \
        --design assets/rendercv/design.yaml --locale-catalog assets/rendercv/locale.yaml
"""

import argparse
import re

import bibtexparser
import yaml
from bibtexparser.bparser import BibTexParser
from bibtexparser.customization import convert_to_unicode

SECTION_TITLE = "Publications"
# The publications are placed right after this section (or at the end if it is missing).
INSERT_AFTER = "Education"


def clean(text):
    """Remove the BibTeX braces and collapse whitespace."""
    return re.sub(r"\s+", " ", text.replace("{", "").replace("}", "")).strip()


def format_author(author, own_last_name):
    """Turn "Last, First" into "First Last", bold the CV owner and keep equal-contribution marks."""
    author = clean(author)
    equal_contribution = "*" in author
    author = author.replace("*", "").strip()
    if "," in author:
        last, first = (part.strip() for part in author.split(",", 1))
        author = f"{first} {last}"
    if own_last_name and own_last_name in author:
        author = f"**{author}**"
    if equal_contribution:
        author += "\\*"
    return author


def to_publication(entry, own_last_name):
    title = clean(entry["title"])
    # The title itself links to the publication (its DOI, or else its URL); the design template
    # therefore leaves out RenderCV's separate link, so `doi`/`url` are not passed on.
    if entry.get("doi"):
        link = f"https://doi.org/{clean(entry['doi'])}"
    else:
        link = clean(entry.get("url", ""))
    publication = {
        "title": f"[{title}]({link})" if link else title,
        "authors": [format_author(a, own_last_name) for a in re.split(r"\s+and\s+", entry.get("author", ""))],
    }
    venue = clean(entry.get("booktitle") or entry.get("journal") or "")
    if "*" in entry.get("author", ""):
        # RenderCV puts a summary above the authors, so the note goes after the venue instead.
        venue = f"{venue}. \\* Equal contribution" if venue else "\\* Equal contribution"
    if venue:
        publication["journal"] = venue
    if entry.get("year"):
        # An integer, so RenderCV shows just the year (a string "2026" is rendered as "Jan 2026").
        publication["date"] = int(clean(entry["year"]))
    return publication


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--cv", default="_data/cv.yml")
    parser.add_argument("--bib", default="_bibliography/papers.bib")
    parser.add_argument("--output", default="_data/.cv_with_publications.yml")
    args = parser.parse_args()

    with open(args.cv, encoding="utf-8") as f:
        data = yaml.safe_load(f)

    bib_parser = BibTexParser(common_strings=True)
    bib_parser.customization = convert_to_unicode
    # `common_strings` only knows the abbreviated months (jun); also accept unquoted full names (month=june).
    for month in ("january february march april may june july august september october november december").split():
        bib_parser.bib_database.strings.setdefault(month, month.capitalize())
    with open(args.bib, encoding="utf-8") as f:
        entries = bibtexparser.load(f, parser=bib_parser).entries

    own_last_name = data["cv"]["name"].split()[-1]
    # Newest first; Python's sort is stable, so entries of the same year keep the order of papers.bib.
    entries.sort(key=lambda e: int(e.get("year", 0) or 0), reverse=True)
    publications = [to_publication(e, own_last_name) for e in entries]

    sections = data["cv"].get("sections") or {}
    sections.pop(SECTION_TITLE, None)
    merged = {}
    for title, section in sections.items():
        merged[title] = section
        if title == INSERT_AFTER:
            merged[SECTION_TITLE] = publications
    merged.setdefault(SECTION_TITLE, publications)
    data["cv"]["sections"] = merged

    with open(args.output, "w", encoding="utf-8") as f:
        f.write("# Generated by bin/rendercv_publications.py from _data/cv.yml and _bibliography/papers.bib; do not edit.\n")
        yaml.safe_dump(data, f, sort_keys=False, allow_unicode=True, width=1000)
    print(f"Wrote {args.output} with {len(publications)} publications")


if __name__ == "__main__":
    main()
